// Une los píxeles iguales seguidos de cada fila en un solo rect.
function pixelMapRects(rows) {
  let out = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      let w = 1;
      while (row[x + w] === row[x]) w++;
      if (row[x] !== ".")
        out += `<rect x="${x * 2}" y="${y * 2}" width="${w * 2}" height="2" fill="${PIXEL_PAL[row[x]]}"/>`;
      x += w;
    }
  });
  return out;
}
// El candado conserva el arco en su propio grupo para animarlo al abrir el Vault.
function mapIcon(id) {
  const body =
    id === "lock"
      ? `<g class="pixel-lock-shackle">${pixelMapRects(PIXEL_MAPS.lock_shackle)}</g>${pixelMapRects(PIXEL_MAPS.lock_body)}`
      : pixelMapRects(PIXEL_MAPS[id] || PIXEL_MAPS.projects);
  return `<svg class="os-icon os-icon--${id} pixel-map" viewBox="0 0 32 32" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}
